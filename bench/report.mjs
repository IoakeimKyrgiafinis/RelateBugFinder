#!/usr/bin/env node
// Aggregate bench/results/bugsinpy.jsonl into bench/RESULTS.md.   Usage: node bench/report.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const rows = fs.readFileSync(path.join(here, "results", "bugsinpy.jsonl"), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
// Latest record per bug wins (re-runs append).
const byBug = new Map(rows.map((r) => [r.bug, r]));
const all = [...byBug.values()];

const METHODS = [
  ["blast", "**Relate Bug Finder**"],
  ["blastDeep", "**Relate Bug Finder + Deep trace** (one recorded re-run of the failing test)"],
  ["blastSbfl", "**Relate Bug Finder + Deep trace + related passing tests** (spectrum, Ochiai; same as Deep trace when no related test was found)"],
  ["stack", "Read the stack top-down"],
  ["sentry", "Stack frames, most recently changed first (Sentry-style)"],
  ["recent", "Most recently changed functions (ignores the trace)"],
];
const isAssert = (r) => !r.message || /^AssertionError/.test(r.message);
const scored = all.filter((r) => r.stage === "reproduced" && r.truth?.length);
// Same split as bench/tune.mjs: weights were chosen on DEV only, so HELD-OUT is the honest number.
const fnv = (s) => { let h = 0x811c9dc5; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 0x01000193) >>> 0; return h; };
const held = scored.filter((r) => fnv(r.bug) % 2 === 1);
const groups = [
  ["Held-out half (never used to choose weights)", held],
  ["All reproduced bugs", scored],
  ["Crashes (an exception other than AssertionError)", scored.filter((r) => !isAssert(r))],
  ["Wrong output (AssertionError in a test)", scored.filter(isAssert)],
  ["Crashes where the fixed function is NOT on the stack", scored.filter((r) => !isAssert(r) && !r.truthOnStack)],
  ["Bugs whose fixed function changed in the 30 days before", scored.filter((r) => r.truthChangedInWindow)],
];

const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : "–");
function table(set) {
  const lines = ["| Method | Top 1 | Top 3 | Top 5 | MRR |", "|---|---|---|---|---|"];
  for (const [k, label] of METHODS) {
    const ranks = set.map((r) => (k === "blastSbfl" ? r.ranks?.blastSbfl ?? r.ranks?.blastDeep : r.ranks?.[k]) ?? null);
    const at = (n) => ranks.filter((x) => x !== null && x <= n).length;
    const mrr = ranks.reduce((s, x) => s + (x ? 1 / x : 0), 0) / (set.length || 1);
    lines.push(`| ${label} | ${at(1)} (${pct(at(1), set.length)}) | ${at(3)} (${pct(at(3), set.length)}) | ${at(5)} (${pct(at(5), set.length)}) | ${mrr.toFixed(2)} |`);
  }
  return lines.join("\n");
}

const stages = {};
for (const r of all) stages[r.stage] = (stages[r.stage] ?? 0) + 1;
const noTruth = all.filter((r) => r.stage === "reproduced" && !r.truth?.length).length;

let md = `# Real-bug benchmark: BugsInPy

Generated by \`node bench/report.mjs\` from \`bench/results/bugsinpy.jsonl\` (${all.length} bugs attempted).

**Setup.** [BugsInPy](https://github.com/soarsmu/BugsInPy) (Widyasari et al., ESEC/FSE 2020) is a published set of real bugs from real Python projects, each with the buggy commit, the fix commit and the test that exposes the bug. For every bug, \`bench/bugsinpy.mjs\` checks out the buggy commit with its real git history, adds the failing test from the fix (committed with an old date so it carries no "recent change" signal), runs it on Python 3.8 / Windows 11, and gives the resulting output to each method below with the clock pinned to the buggy commit's time.

**Ground truth.** The functions whose lines the real fix changed (test files excluded). A method "hits at top k" if any of them is in its first k suggestions. MRR = mean of 1/rank (0 when not found).

**Tuning.** Relate Bug Finder's weights (src/core/analysis.ts \`SCORING\`) were picked by \`node bench/tune.mjs\` on a fixed DEV half of the bugs (split by a hash of the bug name). The first table below is the other half, which played no part in choosing them. For the related-passing-tests row, only tests that passed are used (one that failed or errored is skipped), stack frames are not penalised, and the Ochiai exponent (0.25) was chosen on DEV; at exponent 1, plain Ochiai, it made the ranking worse on both halves.

**Methods compared.** Relate Bug Finder, and three baselines computed from the same trace and graph: reading the stack top-down; the stack frames re-ordered by most recent change (what Sentry's "suspect commits" uses); and the most recently changed functions in the project, ignoring the trace.

## Reproduction

| Outcome | Bugs |
|---|---|
${Object.entries(stages).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${{ reproduced: "Reproduced (test fails as in the dataset)", "test-passed": "Test passed on this machine (not reproduced)", "env-error": "Environment broke before reaching project code", venv: "Python environment could not be built", error: "Harness error (clone/checkout)" }[k] ?? k} | ${v} |`).join("\n")}

${noTruth ? `${noTruth} reproduced bug(s) are excluded from scoring because the fix only changed module-level code (no function to point at).\n` : ""}
## Results
`;
for (const [title, set] of groups) md += `\n### ${title} (n = ${set.length})\n\n${set.length ? table(set) : "_none_"}\n`;

// Lines inside the fixed function (deep trace line recording).
{
  const withLines = scored.filter((r) => r.lines?.per?.some((p) => p.ran > 0));
  const avg = (set, f) => (set.length ? (set.reduce((s, r) => s + f(r), 0) / set.length).toFixed(1) : "–");
  const first = (r) => r.lines.per.find((p) => p.ran > 0);
  // The panel shows the failing-only lines when there are any, else the lines that ran.
  const only = withLines.filter((r) => first(r).failingOnly > 0);
  const shownHit = (r) => (first(r).failingOnly > 0 ? first(r).fixedInFailingOnly : first(r).fixedRan);
  const shownLen = (r) => (first(r).failingOnly > 0 ? first(r).failingOnly : first(r).ran);
  md += `\n## Lines inside the fixed function\n\nAfter a deep trace the panel lists, for each suspect, the lines that ran in the failing test. After comparing with related passing tests, it lists the lines that ran **only in the failing test** instead, when there are any. Clicking highlights them in the editor. Ground truth: the lines the real fix changed.\n\n`;
  md += `| | Bugs | A fixed line is listed | Lines listed (avg) | Function length (avg) |\n|---|---|---|---|---|\n`;
  md += `| Lines that ran in the failing test | ${withLines.length} | ${pct(withLines.filter((r) => first(r).fixedRan).length, withLines.length)} | ${avg(withLines, (r) => first(r).ran)} | ${avg(withLines, (r) => first(r).len)} |\n`;
  md += `| Lines that ran only in the failing test (when there are any) | ${only.length} | ${pct(only.filter((r) => first(r).fixedInFailingOnly).length, only.length)} | ${avg(only, (r) => first(r).failingOnly)} | ${avg(only, (r) => first(r).len)} |\n`;
  md += `| **What the panel shows** (the above, else the lines that ran) | ${withLines.length} | ${pct(withLines.filter(shownHit).length, withLines.length)} | ${avg(withLines, shownLen)} | ${avg(withLines, (r) => first(r).len)} |\n`;
  md += `\nA fix that only adds code (no old line changed inside the function) blames the lines around the insertion.\n`;
}

md += `\n## Per bug\n\n| Bug | Kind | Fixed function | On stack | Changed ≤30d | Blast | +Deep | +Passing tests | Stack | Sentry | Recent |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of scored.sort((a, b) => a.bug.localeCompare(b.bug, undefined, { numeric: true }))) {
  const f = (x) => (x === null || x === undefined ? "–" : `#${x}`);
  md += `| ${r.bug} | ${isAssert(r) ? "assert" : (r.message ?? "").split(":")[0].slice(0, 22)} | \`${r.truth[0].split("#")[1]}\`${r.truth.length > 1 ? ` +${r.truth.length - 1}` : ""} | ${r.truthOnStack ? "yes" : "no"} | ${r.truthChangedInWindow ? "yes" : "no"} | ${f(r.ranks.blast)} | ${f(r.ranks.blastDeep)} | ${f(r.ranks.blastSbfl)} | ${f(r.ranks.stack)} | ${f(r.ranks.sentry)} | ${f(r.ranks.recent)} |\n`;
}
fs.writeFileSync(path.join(here, "RESULTS.md"), md);
console.log(md.split("## Per bug")[0]);
